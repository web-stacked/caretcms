// Writes static/cms/editor/messages.js: the on-page editor's English messages,
// built from src/runtime/i18n.ts. The asset route serves the site's locale in
// its place; this file is what a bundler resolves when the editor is imported
// as a module (`@caretcms/core/editor-runtime`). Runs after `tsc`.
import { writeFile } from "node:fs/promises";
import { EN_STUDIO_MESSAGES, editorMessages } from "../dist/runtime/i18n.js";

const target = new URL("../static/cms/editor/messages.js", import.meta.url);
const messages = JSON.stringify(editorMessages(EN_STUDIO_MESSAGES), null, 2);
await writeFile(target, `// Generated by scripts/write-editor-messages.mjs from src/runtime/i18n.ts. Do not edit.\nexport default ${messages};\n`);
