export function resolveStudioDictionary(
  locale: StudioLocale = "en",
  overrides: StudioDictionary = {},
): ResolvedStudioDictionary {
  return {
    ...EN_STUDIO_MESSAGES,
    ...(locale === "es" ? ES_STUDIO_MESSAGES : {}),
    ...overrides,
  };
}

/** The on-page editor's messages: the `editor.*` keys of a resolved dictionary. */
export function editorMessages(messages: ResolvedStudioDictionary): Record<string, string> {
  return Object.fromEntries(Object.entries(messages).filter(([key]) => key.startsWith("editor.")));
}
